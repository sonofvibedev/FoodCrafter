/** Номер следующей версии по типу изменения. Локальные правки считаются пачкой. */
export function bumpVersion(prev: string, kind: ChangeKind, localChanges = 1): string {
  const [major = 1, minor = 0, patch = 0, local = 0] = prev.split('.').map(Number)

  if (kind === 'global') return `${major}.${minor + 1}`
  if (kind === 'important') return `${major}.${minor}.${patch + 1}`
  return `${major}.${minor}.${patch}.${String(local + localChanges).padStart(4, '0')}`
}
